#!/bin/zsh
# Keeps the build machine's paths (and so its user name) out of release binaries.
#
#   release-paths.sh xcconfig PROJECT_DIR OUTPUT
#       Write an Xcode configuration for XCODE_XCCONFIG_FILE. It maps the project
#       and home folders out of compiled-in file names (__FILE__, #filePath, debug
#       info) and builds Metal shaders without debug info or embedded sources.
#   release-paths.sh strip APP
#       Remove debugging symbols, including the debug map that records every
#       object file's absolute path, from each Mach-O file in APP. Signatures
#       become invalid; package-release.sh signs everything afterwards.
set -euo pipefail

usage() {
  print -u2 "Usage: $0 xcconfig PROJECT_DIR OUTPUT | strip APP"
  exit 2
}

write_xcconfig() {
  local project="${1:A}" output="$2" home="${HOME:A}"
  # Clang applies the longest matching prefix and Swift the first listed one,
  # so the project folder is listed before the home folder that contains it.
  local c_maps="\"-ffile-prefix-map=$project=OmniTerm\" \"-ffile-prefix-map=$home=~\""
  local swift_maps="-file-prefix-map \"$project=OmniTerm\" -file-prefix-map \"$home=~\""
  mkdir -p "${output:h}"
  # Swift's prefix map covers debug info but not #file, which Swift 5 code
  # expands to an absolute path. ConciseMagicFile (the Swift 6 default) makes it
  # Module/File.swift. Swift 6 targets warn if it is enabled again, and some
  # treat warnings as errors, so it is selected by each target's SWIFT_VERSION.
  print -r -- "// Generated by scripts/release-paths.sh for release builds; do not edit.
OTHER_CFLAGS = \$(inherited) $c_maps
OMNITERM_CONCISE_FILE_5 = -enable-upcoming-feature ConciseMagicFile
OTHER_SWIFT_FLAGS = \$(inherited) \$(OMNITERM_CONCISE_FILE_\$(SWIFT_VERSION:base)) $swift_maps
MTL_ENABLE_DEBUG_INFO = NO" > "$output"
}

strip_debug_symbols() {
  local app="$1" item stripped=0
  [[ -d "$app" ]] || { print -u2 "No app bundle at $app"; exit 1; }
  while IFS= read -r -d '' item; do
    [[ -L "$item" ]] && continue
    file -b "$item" | grep -q 'Mach-O' || continue
    # strip warns that the signature becomes invalid; it is re-signed later.
    strip -S "$item" 2>/dev/null || { print -u2 "Could not strip $item"; exit 1; }
    stripped=$((stripped + 1))
  done < <(find "$app" -type f -print0)
  print -- "Stripped debugging symbols from $stripped Mach-O files."
  local remaining
  remaining="$(grep -r -a -l -F -- "${HOME:A}/" "$app" 2>/dev/null || true)"
  if [[ -n "$remaining" ]]; then
    print -u2 "Files that still name ${HOME:A}:"
    print -u2 -r -- "$remaining"
  fi
}

case "${1:-}" in
  xcconfig) (( $# == 3 )) || usage; write_xcconfig "$2" "$3" ;;
  strip) (( $# == 2 )) || usage; strip_debug_symbols "$2" ;;
  *) usage ;;
esac
